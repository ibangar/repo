export const EXERCISE_MAP: Record<string, ExerciseDef> = Object.fromEntries(EXERCISES.map(e => [e.id, e]))

export function getExercise(id: string): ExerciseDef {
  const e = EXERCISE_MAP[id]
  if (!e) throw new Error(`Unknown exercise: ${id}`)
  return e
}

/** Exercises that can stand in for `id` (same movement pattern). */
export function swapCandidates(id: string, available?: Set<string>): ExerciseDef[] {
  const base = getExercise(id)
  return EXERCISES.filter(e =>
    e.id !== id && e.pattern === base.pattern &&
    (!available || e.equipment.every(eq => eq === 'bodyweight' || eq === 'bench' || available.has(eq))),
  )
}

